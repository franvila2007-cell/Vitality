// Expanded built-in foods, layered UNDER the coach's foods_global table (rows
// in the database always win on a name collision, so nothing a coach curated
// is ever overridden). Lives in code, not the database, so it versions with
// the parser and needs no data migration.
//
// Numbers are per 100g (or 100ml for drinks) unless the entry is perUnit /
// dish. They are good-faith nutrition-label-grade estimates, not lab values.
import type { FoodEntry, StatefulMacros, UnitFields } from './foodDb';

const p = (cal: number, prot: number, carb: number, fat: number, defaultGrams: number, x: UnitFields = {}): FoodEntry =>
  ({ type: 'per100g', cal, prot, carb, fat, defaultGrams, ...x });
const drink = (cal: number, prot: number, carb: number, fat: number, defaultMl: number, x: UnitFields = {}): FoodEntry =>
  ({ type: 'per100g', cal, prot, carb, fat, defaultGrams: defaultMl, liquid: true, cupGrams: 240, ...x });
const u = (cal: number, prot: number, carb: number, fat: number, label: string, avgGrams: number): FoodEntry =>
  ({ type: 'perUnit', cal, prot, carb, fat, label, avgGrams });
const d = (cal: number, prot: number, carb: number, fat: number, avgGrams: number): FoodEntry =>
  ({ type: 'dish', cal, prot, carb, fat, avgGrams });
const m = (raw: [number, number, number, number], cooked: [number, number, number, number], defaultGrams: number): FoodEntry => {
  const mac = (a: [number, number, number, number]): StatefulMacros => ({ cal: a[0], prot: a[1], carb: a[2], fat: a[3] });
  return { type: 'per100g', raw: mac(raw), cooked: mac(cooked), defaultGrams };
};

