-- 8-Week Challenge weekly check-in (public /challenge/check-in, one shared
-- link; the form recognises each member by email, then phone). Temporary,
-- like challenge_intakes (0018), and the same security model: rows are only
-- ever written server-side by /api/challenge/check-in with the service-role
-- key after re-validation, so the anon key gets no policy at all. Only the
-- coach can read.

-- Members who check in without an intake on file (or matched one by phone):
-- their goal is asked once and remembered here, keyed by email.
create table public.challenge_member_goals (
  email text primary key,                -- stored lowercased
  goal text not null check (goal in ('Lose fat', 'Build muscle', 'More energy & routine')),
  start_weight_kg numeric(5, 1),
  start_date date not null default current_date,
  full_name text,
  phone text,
  -- set when the email itself isn't on an intake but the phone number matched one
  intake_id uuid references public.challenge_intakes(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table public.challenge_checkins (
  id uuid primary key default gen_random_uuid(),
  -- generated by the browser once per check-in; a double-submit lands once
  submission_id uuid not null unique,
  created_at timestamptz not null default now(),
  intake_id uuid references public.challenge_intakes(id) on delete set null,
  crm_contact_id uuid references public.crm_contacts(id) on delete set null,
  email text not null,
  phone text,
  full_name text,
  goal text,
  week_number int not null check (week_number between 1 and 8),
  weight_kg numeric(5, 1),
  waist_cm numeric(5, 1),
  feeling int check (feeling between 1 and 10),
  answers jsonb not null default '{}',   -- goal-specific answers
  biggest_win text not null,
  hardest text,
  need_from_us text,
  photo_paths text[] not null default '{}',  -- in the private challenge-checkins bucket
  needs_review boolean not null default false  -- no intake found for this member
);

create index challenge_checkins_email_idx on public.challenge_checkins (email, week_number);
create index challenge_checkins_created_idx on public.challenge_checkins (created_at desc);

alter table public.challenge_member_goals enable row level security;
alter table public.challenge_checkins enable row level security;

create policy "challenge_member_goals_select_coach" on public.challenge_member_goals for select using (public.is_coach());
create policy "challenge_checkins_select_coach" on public.challenge_checkins for select using (public.is_coach());

-- Private bucket for progress photos. No storage policies: members upload
